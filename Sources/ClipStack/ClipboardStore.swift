import AppKit
import CryptoKit
import ImageIO

struct ClipItem: Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    let kind: Kind
    var text: String?
    var imageHash: String?
    var pixelWidth: Int?
    var pixelHeight: Int?
    var paths: [String]?
    let date: Date

    private enum CodingKeys: String, CodingKey {
        case kind, text, imageHash, pixelWidth, pixelHeight, paths, date
    }

    init(kind: Kind, text: String? = nil, imageHash: String? = nil,
         pixelWidth: Int? = nil, pixelHeight: Int? = nil,
         paths: [String]? = nil, date: Date = Date()) {
        self.kind = kind
        self.text = text
        self.imageHash = imageHash
        self.pixelWidth = pixelWidth
        self.pixelHeight = pixelHeight
        self.paths = paths
        self.date = date
    }

    // Tolerant decode so pre-image-support history files (text-only, no `kind`) still load.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        kind = try c.decodeIfPresent(Kind.self, forKey: .kind) ?? .text
        text = try c.decodeIfPresent(String.self, forKey: .text)
        imageHash = try c.decodeIfPresent(String.self, forKey: .imageHash)
        pixelWidth = try c.decodeIfPresent(Int.self, forKey: .pixelWidth)
        pixelHeight = try c.decodeIfPresent(Int.self, forKey: .pixelHeight)
        paths = try c.decodeIfPresent([String].self, forKey: .paths)
        date = try c.decodeIfPresent(Date.self, forKey: .date) ?? Date()
    }

    var dedupeKey: String {
        switch kind {
        case .text: return "t:" + (text ?? "")
        case .image: return "i:" + (imageHash ?? "")
        case .files: return "f:" + (paths ?? []).joined(separator: "\n")
        }
    }
}

final class ClipboardStore {
    private(set) var items: [ClipItem] = []
    let maxItems = 100
    private let maxImageBytes = 10 * 1024 * 1024

    private let saveURL: URL
    private let imagesDir: URL
    private var lastChangeCount: Int
    private var thumbCache: [String: NSImage] = [:]

    // Marker types clipboard-aware apps use to say "don't record this"
    // (password managers set ConcealedType; transient covers autogenerated content).
    private static let skipTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    ]

    init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipStack", isDirectory: true)
        imagesDir = dir.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        saveURL = dir.appendingPathComponent("history.json")
        lastChangeCount = NSPasteboard.general.changeCount
        load()
    }

    /// Checks the pasteboard for new content. Cheap when nothing changed
    /// (changeCount comparison only, no content read).
    ///
    /// Capture priority: copied files, then text, then images. Text beats images
    /// because apps like Excel put an image render of cells alongside the text.
    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        guard let types = pb.types else { return }
        if Self.skipTypes.contains(where: types.contains) { return }

        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            add(ClipItem(kind: .files, paths: urls.map(\.path)))
            return
        }

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(ClipItem(kind: .text, text: text))
            return
        }

        if types.contains(.png) || types.contains(.tiff) {
            captureImage(from: pb)
        }
    }

    func add(_ item: ClipItem) {
        items.removeAll { $0.dedupeKey == item.dedupeKey }
        items.insert(item, at: 0)
        while items.count > maxItems {
            deleteAssets(of: items.removeLast())
        }
        save()
    }

    func clear() {
        items.forEach(deleteAssets)
        items.removeAll()
        thumbCache.removeAll()
        save()
    }

    /// Puts an item back on the system pasteboard.
    func restore(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            guard let hash = item.imageHash,
                  let data = try? Data(contentsOf: imageURL(for: hash)) else { return }
            pb.setData(data, forType: .png)
            if let rep = NSBitmapImageRep(data: data), let tiff = rep.tiffRepresentation {
                pb.setData(tiff, forType: .tiff)
            }
        case .files:
            let urls = (item.paths ?? []).map { NSURL(fileURLWithPath: $0) }
            if !urls.isEmpty {
                pb.writeObjects(urls)
            }
        }
    }

    /// Small menu thumbnail for an image item (cached; ~48pt max, 2x for retina).
    func thumbnail(for item: ClipItem) -> NSImage? {
        guard let hash = item.imageHash else { return nil }
        if let cached = thumbCache[hash] { return cached }
        guard let image = NSImage(contentsOf: thumbURL(for: hash)) else { return nil }
        image.size = NSSize(width: image.size.width / 2, height: image.size.height / 2)
        thumbCache[hash] = image
        return image
    }

    // MARK: - Image capture

    private func captureImage(from pb: NSPasteboard) {
        var pngData: Data?
        if let png = pb.data(forType: .png) {
            pngData = png
        } else if let tiff = pb.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: tiff) {
            pngData = rep.representation(using: .png, properties: [:])
        }
        guard let data = pngData, !data.isEmpty, data.count <= maxImageBytes else { return }

        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()

        // Same image copied again: just move the existing entry to the top.
        if let existing = items.first(where: { $0.imageHash == hash }) {
            add(existing)
            return
        }

        var width = 0, height = 0
        if let src = CGImageSourceCreateWithData(data as CFData, nil),
           let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any] {
            width = props[kCGImagePropertyPixelWidth] as? Int ?? 0
            height = props[kCGImagePropertyPixelHeight] as? Int ?? 0
        }

        try? data.write(to: imageURL(for: hash), options: .atomic)
        writeThumbnail(from: data, hash: hash)
        add(ClipItem(kind: .image, imageHash: hash, pixelWidth: width, pixelHeight: height))
    }

    private func writeThumbnail(from data: Data, hash: String) {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 96,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, options as CFDictionary) else { return }
        let rep = NSBitmapImageRep(cgImage: cg)
        guard let thumbPNG = rep.representation(using: .png, properties: [:]) else { return }
        try? thumbPNG.write(to: thumbURL(for: hash), options: .atomic)
    }

    // MARK: - Storage

    private func imageURL(for hash: String) -> URL {
        imagesDir.appendingPathComponent("\(hash).png")
    }

    private func thumbURL(for hash: String) -> URL {
        imagesDir.appendingPathComponent("\(hash).thumb.png")
    }

    private func deleteAssets(of item: ClipItem) {
        guard let hash = item.imageHash else { return }
        try? FileManager.default.removeItem(at: imageURL(for: hash))
        try? FileManager.default.removeItem(at: thumbURL(for: hash))
        thumbCache[hash] = nil
    }

    private func load() {
        guard let data = try? Data(contentsOf: saveURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: saveURL, options: .atomic)
    }
}
